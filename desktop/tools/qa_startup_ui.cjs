const { chromium }=require('C:/Users/ninja/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const ROOT=path.resolve(__dirname,'..'),OUT=process.env.LINDA_UI_OUT||path.join(ROOT,'evidence','ui');
fs.mkdirSync(OUT,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const base='http://127.0.0.1:18764';
 const res=await fetch(base+'/api/status',{headers:{'x-linda-token':'ui-test-token'}});
 const original=await res.json(),results=[];
 const source=await (await fetch(base)).text();
 for(const lang of ['en','pl','ru'])for(const theme of ['dark','light','contrast'])for(const size of [[1360,900],[980,640],[480,720]]){
  const context=await browser.newContext({viewport:{width:size[0],height:size[1]},reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const state=structuredClone(original);
  state.models_ready=true;state.installed_version='1.3.4.1';state.settings={...state.settings,language:lang,theme,preload:true,tour_done:true,quality:'both'};
  state.engine={...state.engine,phase:'loading',tier:'full',device:'dml',have_pro:true,have_lite:true};state.startup={phase:'warming',error:''};
  const boot=Buffer.from(JSON.stringify({language:lang,version:'2.1.0.0',settings:state.settings})).toString('base64');
  const html=source.replace(/atob\('[A-Za-z0-9+/=]+'\)/,`atob('${boot}')`);
  await page.addInitScript(()=>localStorage.setItem('linda_lang','ru'));
  await page.route(base+'/',r=>r.fulfill({contentType:'text/html',body:html}));
  await page.route('**/api/status',r=>r.fulfill({json:state}));
  await page.goto(base,{waitUntil:'networkidle'});
  await page.locator('#startupStatus').filter({hasText:lang==='en'?'Warming':lang==='pl'?'Rozgrzewanie':'Прогрев'}).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'),lang);
  await page.locator('#lindaStartup').waitFor({state:'visible'});
  assert.equal(await page.locator('.startup-frame').count(),5,'all five Linda illustrations must be embedded');
  const layout=await page.locator('.startup-card').evaluate(el=>{const b=el.getBoundingClientRect();return {x:b.x,right:b.right,w:innerWidth,scroll:document.querySelector('#lindaStartup').scrollWidth}});
  assert(layout.x>=-1&&layout.right<=layout.w+1&&layout.scroll<=layout.w+1,JSON.stringify(layout));
  const name=`${lang}-${theme}-${size.join('x')}`;
  if(size[0]===980)await page.screenshot({path:path.join(OUT,name+'.png')});
  state.startup.phase='error';
  await page.evaluate(s=>window.LINDA_startupRender(s),state);
  await page.locator('#startupContinue').waitFor({state:'visible'});
  await page.locator('#startupContinue').click();
  await page.locator('#lindaStartup').waitFor({state:'hidden'});
  assert.equal(await page.locator('#textInput').evaluate(el=>el.inert),false);
  await page.reload({waitUntil:'networkidle'});
  state.startup.phase='ready';state.engine.phase='ready';
  await page.evaluate(s=>window.LINDA_startupRender(s),state);
  await page.locator('#lindaStartup').waitFor({state:'hidden'});
  state.settings.preload=false;state.startup.phase='pending';
  await page.evaluate(s=>window.LINDA_startupRender(s),state);
  await page.locator('#lindaStartup').waitFor({state:'hidden'});
  state.settings.preload=true;state.models_ready=false;
  await page.evaluate(s=>window.LINDA_startupRender(s),state);
  await page.locator('#lindaStartup').waitFor({state:'hidden'});
  assert.deepEqual(errors,[],name);
  results.push({name,pass:true});await context.close();
 }
 const cycleContext=await browser.newContext({viewport:{width:980,height:640},reducedMotion:'reduce'});
 const cyclePage=await cycleContext.newPage();
 await cyclePage.clock.install();
 const cycleState=structuredClone(original);
 cycleState.models_ready=true;cycleState.startup={phase:'warming',error:''};
 cycleState.settings={...cycleState.settings,language:'en',theme:'dark',preload:true,tour_done:true};
 const cycleBoot=Buffer.from(JSON.stringify({language:'en',version:'2.1.0.0',settings:cycleState.settings})).toString('base64');
 await cyclePage.route(base+'/',r=>r.fulfill({contentType:'text/html',body:source.replace(/atob\('[A-Za-z0-9+/=]+'\)/,`atob('${cycleBoot}')`)}));
 await cyclePage.route('**/api/status',r=>r.fulfill({json:cycleState}));
 await cyclePage.goto(base,{waitUntil:'networkidle'});
 for(let i=0;i<6;i++){
  assert.equal(await cyclePage.locator('.startup-frame.is-active').getAttribute('data-frame'),String(i%5));
  if(i<5)await cyclePage.screenshot({path:path.join(OUT,`panorama-frame-${i+1}.png`)});
  await cyclePage.clock.runFor(6000);
 }
 cycleState.startup.phase='ready';
 await cyclePage.evaluate(s=>window.LINDA_startupRender(s),cycleState);
 await cyclePage.clock.runFor(6000);
 const stoppedFrame=await cyclePage.locator('.startup-frame.is-active').getAttribute('data-frame');
 await cyclePage.clock.runFor(18000);
 assert.equal(await cyclePage.locator('.startup-frame.is-active').getAttribute('data-frame'),stoppedFrame);
 await cycleContext.close();
 fs.writeFileSync(path.join(OUT,'artwork-cycle.json'),JSON.stringify({frames:5,intervalMs:6000,wraparound:true,stopsWhenHidden:true,pass:true},null,2));
 fs.writeFileSync(path.join(OUT,'results.json'),JSON.stringify(results,null,2));
 await browser.close();console.log('PASS',results.length,'language/theme/viewport cases; loading/error/ready/off/no-models; no JS errors');
})().catch(e=>{console.error(e);process.exitCode=1;});
